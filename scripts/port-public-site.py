"""
Port the client's static public site (a single index.html) into the Next.js app.

    python scripts/port-public-site.py [path/to/index.html]

Writes three generated files into web/src/components/site/ (don't edit them by hand —
change the source site and re-run this script):

  site.generated.css   the site's CSS, scoped under `.cs-site` so it can't affect app pages
  markup.generated.ts  the site's <body> markup, split into header / sections / footer / modal
  site.generated.js    the site's script, wrapped as initSite(root, opts) → cleanup()

Why scope/wrap instead of rewriting in React? The site is finished, client-approved design.
Keeping its markup, CSS and behaviour byte-for-byte (apart from the changes listed below)
means a new version from the designer can be dropped in by re-running this script.

Changes applied:
  CSS     every selector prefixed with .cs-site; :root/body → .cs-site; html → html:has(.cs-site);
          .js/.no-js → .cs-site.js/.cs-site.no-js; body.modal-open → body.cs-modal-open;
          @keyframes renamed cs-*; fonts point at the app's next/font variables.
  Markup  split into parts for a multi-page site; in-page anchors → page routes;
          privacy.html/terms.html → /privacy, /terms; "Sign in" (and footer "Platform") links added.
  Script  runs on demand, queries inside the site root, records every listener and timer
          so cleanup can remove them, and sends demo requests through the app's data layer.
          Multi-page tweaks: solid header without a hero; "Practice" opens /training#scenario-N.
"""

