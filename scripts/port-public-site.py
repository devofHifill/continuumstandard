OUT = os.path.join(ROOT, "web", "src", "components", "site")

html = io.open(SRC, encoding="utf-8").read()

HEADER = "/* GENERATED by scripts/port-public-site.py from the client's public site — do not edit. */\n"


# ── CSS ────────────────────────────────────────────────────────────────────
css = html[html.index("<style>") + len("<style>"): html.index("</style>")]
css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)  # drop comments

keyframes = set(re.findall(r"@keyframes\s+([\w-]+)", css))


def scope_selector(sel: str) -> str:
    sel = sel.strip()
    if not sel:
        return sel
    if sel.startswith(":root"):
        return ".cs-site" + sel[len(":root"):]
    if re.match(r"html\b", sel):
        return "html:has(.cs-site)" + sel[4:]
    if sel.startswith("body.modal-open"):
        return "body.cs-modal-open" + sel[len("body.modal-open"):]
    if re.match(r"body\b", sel):
        return ".cs-site" + sel[4:]
    for flag in (".js", ".no-js"):
        if re.match(re.escape(flag) + r"(?![\w-])", sel):
            return ".cs-site" + sel
    return ".cs-site " + sel


def scope_block(text: str) -> str:
    out, i, n = [], 0, len(text)
    while i < n:
        brace = text.find("{", i)
        if brace == -1:
            out.append(text[i:])
            break
        prelude = text[i:brace].strip()
        depth, j = 1, brace + 1
        while j < n and depth:
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
            j += 1
        body = text[brace + 1: j - 1]
        if prelude.startswith("@keyframes"):
            name = prelude.split()[1]
            out.append(f"@keyframes cs-{name} {{{body}}}\n")
        elif prelude.startswith(("@media", "@supports", "@container")):
            out.append(f"{prelude} {{\n{scope_block(body)}}}\n")
        elif prelude.startswith("@"):
            out.append(f"{prelude} {{{body}}}\n")
        else:
            selectors = ", ".join(scope_selector(s) for s in prelude.split(","))
            out.append(f"{selectors} {{{body}}}\n")
        i = j
    return "".join(out)


def rename_animations(text: str) -> str:
    def fix(m):
        value = m.group(2)
        for k in keyframes:
            value = re.sub(rf"(?<![\w-]){re.escape(k)}(?![\w-])", f"cs-{k}", value)
        return m.group(1) + value

    return re.sub(r"(animation(?:-name)?\s*:)([^;}]*)", fix, text)


scoped = rename_animations(scope_block(css))
# Fonts come from next/font (self-hosted) via CSS variables set in the root layout.
